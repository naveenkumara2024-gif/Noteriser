/**
 * Builds eval/RESULTS.md from the result files in eval/results. Nothing here measures anything: it
 * only lays out numbers that were already written by run-verifier, the sweep and kappa, next to
 * the lore's targets, and embeds the hand-written analysis in eval/analysis.md.
 *
 *   npm run eval:report
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { THRESHOLDS } from "../src/core/verify";
import { overFlagBreakdown } from "./lib/analysis";
import { describeCases, FAILURE_TYPES, loadCases, loadRegressions } from "./lib/cases";
import { type DraftResult, fmtRate, type Metrics, pct, type Rate } from "./lib/metrics";

interface ResultFile {
  meta: {
    startedAt: string;
    split: string;
    judge: string;
    judgeLabel: string;
    nliModel: string;
    thresholds: typeof THRESHOLDS;
    wallSeconds: number;
    drafts: number;
    degradedDrafts: number;
    concurrency: number | null;
    latencyMs: { mean: number; p50: number; p95: number };
    usage: { inputTokens: number; outputTokens: number; costUsd: number };
  };
  summary: Metrics;
  results: DraftResult[];
}

const read = <T>(path: string): T | undefined =>
  existsSync(path) ? (JSON.parse(readFileSync(path, "utf8")) as T) : undefined;
const run = (name: string): ResultFile | undefined => read<ResultFile>(`eval/results/${name}.json`);

const devLive = run("dev-live");
const devFake = run("dev-fake");
const devOr = run("dev-live-openrouter");
const devXs = run("dev-fake-xsmall");
const testLive = run("test-live");
const testFake = run("test-fake");

const cell = (r: ResultFile | undefined, pick: (m: Metrics) => Rate): string =>
  r ? fmtRate(pick(r.summary)) : "not run";
const short = (r: Rate): string => `${pct(r.rate)} (${r.k}/${r.n})`;
const sCell = (r: ResultFile | undefined, pick: (m: Metrics) => Rate): string =>
  r ? short(pick(r.summary)) : "not run";

const out: string[] = [];
const line = (s = ""): number => out.push(s);

const cases = loadCases();
const dev = describeCases(cases.filter((c) => c.split === "dev"));
const test = describeCases(cases.filter((c) => c.split === "test"));

line("# Evaluation results");
line();
line(
  "Generated by `npm run eval:report` from the files in `eval/results/`. Nothing on this page was edited by hand except the analysis section, which is `eval/analysis.md`. Numbers are reported as measured; where a lore target is missed, it says so.",
);
line();
line("## How to read this");
line();
line(
  "- **Verifier recall** = bad drafts that were *not* passed as SUPPORTED (flagged PARTIAL counts as caught; the stricter *rejected outright* rate is shown too). **Over-flag rate** = good drafts that were *not* SUPPORTED. These follow lore section 8.5.",
);
line(
  `- **Sample sizes are small.** ${dev.bad} bad and ${dev.good} good drafts per split. Every rate carries a 95% Wilson interval; a difference of one or two drafts is noise.`,
);
line(
  "- **Labels were written by the same author as the cases** (no independent annotators), and the test split was written alongside the dev split, not by someone else. Treat the numbers as a regression-grade measurement of this verifier on this kind of text, not as a general accuracy claim.",
);
line(
  "- **Tuning discipline.** Thresholds were examined on the dev split only. The test split was run once, after the threshold recommendation was written to `eval/thresholds.recommended.json`; nothing was changed afterwards. The recommendation was to keep the current thresholds, so the test numbers are for the thresholds that were already in force.",
);
line(
  "- Verdicts come from the real verifier with the real entailment model (`Xenova/nli-deberta-v3-small`). The judge is either a live model (named per column) or a neutral stand-in that always passes (`fake`), which measures the other three checks on their own.",
);
line();

line("## The case set");
line();
line(
  `${cases.length} original lecture-note excerpts, 8 subjects, each with good drafts and drafts with one planted failure. Split by a fixed rule (sorted by id; even position dev, odd position test).`,
);
line();
line("| | cases | good drafts | bad drafts |");
line("|---|---:|---:|---:|");
line(`| dev | ${dev.cases} | ${dev.good} | ${dev.bad} |`);
line(`| test | ${test.cases} | ${test.good} | ${test.bad} |`);
line();
line("| failure type | dev | test |");
line("|---|---:|---:|");
for (const t of FAILURE_TYPES) line(`| ${t} | ${dev.byType[t] ?? 0} | ${test.byType[t] ?? 0} |`);
line();

line("## Headline numbers against the lore targets");
line();
line(
  "| metric | target | dev, live judge | test, live judge | dev, neutral judge | test, neutral judge |",
);
line("|---|---|---|---|---|---|");
const row = (name: string, target: string, pick: (m: Metrics) => Rate) =>
  line(
    `| ${name} | ${target} | ${cell(devLive, pick)} | ${cell(testLive, pick)} | ${cell(devFake, pick)} | ${cell(testFake, pick)} |`,
  );
row("Verifier recall (bad drafts not SUPPORTED)", ">= 90%", (m) => m.recall);
row("...rejected outright (UNSUPPORTED or CONTRADICTED)", "-", (m) => m.hardRecall);
row("Over-flag rate (good drafts not SUPPORTED)", "<= 15%", (m) => m.overFlag);
row("...rejected outright", "-", (m) => m.overReject);
row("Citation validity (of drafts let through)", "100%", (m) => m.citationValidity);
line();
const bal = (r?: ResultFile) => (r ? pct(r.summary.balancedAccuracy) : "not run");
line(
  `Balanced accuracy: dev live ${bal(devLive)}, test live ${bal(testLive)}, dev neutral ${bal(devFake)}, test neutral ${bal(testFake)}.`,
);
line(
  `Bad drafts passed as SUPPORTED (the harmful misses): dev live ${devLive?.summary.slipped ?? "n/a"}, test live ${testLive?.summary.slipped ?? "n/a"}, dev neutral ${devFake?.summary.slipped ?? "n/a"}, test neutral ${testFake?.summary.slipped ?? "n/a"}.`,
);
line();
line("| lore target | status on the test split (live judge) |");
line("|---|---|");
if (testLive) {
  const m = testLive.summary;
  line(
    `| Verifier recall >= 90% | ${m.recall.rate >= 0.9 ? "met" : "**missed**"} (${pct(m.recall.rate)}; rejected outright ${pct(m.hardRecall.rate)}) |`,
  );
  line(
    `| Over-flag rate <= 15% | ${m.overFlag.rate <= 0.15 ? "met" : "**missed**"} (${pct(m.overFlag.rate)}) |`,
  );
  line(
    `| Citation validity 100% | ${m.citationValidity.rate === 1 ? "met" : "**missed**"} (${pct(m.citationValidity.rate)}) |`,
  );
} else {
  line("| all | the test split has not been run yet |");
}
line();

line("## Recall by failure type");
line();
line("Share of bad drafts not passed as SUPPORTED. Live judge unless stated.");
line();
line("| failure type | dev | test | dev, neutral judge | test, neutral judge |");
line("|---|---|---|---|---|");
const byType = (r: ResultFile | undefined, t: string): string => {
  const x = r?.summary.byType[t];
  return x ? `${x.caught.k}/${x.caught.n}` : "not run";
};
for (const t of FAILURE_TYPES) {
  line(
    `| ${t} | ${byType(devLive, t)} | ${byType(testLive, t)} | ${byType(devFake, t)} | ${byType(testFake, t)} |`,
  );
}
line();

line("## Latency and cost");
line();
line(
  "Verification only (nothing is generated). The judge runs on every draft here so the sweep has its answer; in the app it is skipped when the other checks have already settled the verdict.",
);
line();
line("| run | drafts | wall time | per draft: mean / median / p95 | tokens in / out | cost |");
line("|---|---:|---:|---|---|---|");
for (const [name, r] of [
  ["dev, live judge (Nara)", devLive],
  ["dev, live judge (OpenRouter)", devOr],
  ["test, live judge", testLive],
  ["dev, neutral judge", devFake],
  ["test, neutral judge", testFake],
] as const) {
  if (!r) continue;
  line(
    `| ${name} | ${r.meta.drafts} | ${r.meta.wallSeconds}s | ${(r.meta.latencyMs.mean / 1000).toFixed(1)}s / ${(r.meta.latencyMs.p50 / 1000).toFixed(1)}s / ${(r.meta.latencyMs.p95 / 1000).toFixed(1)}s | ${r.meta.judge === "fake" ? "no model calls" : `${r.meta.usage.inputTokens} / ${r.meta.usage.outputTokens}`} | ${r.meta.judge === "fake" ? "n/a" : `$${r.meta.usage.costUsd.toFixed(4)} (free models)`} |`,
  );
}
line();
line(
  "The live runs used 2-3 parallel calls on free models, so latency includes queueing and provider rate limits. The neutral-judge runs are the entailment model and local checks only (one draft at a time).",
);
line();

const sweep = read<{
  gridSize: number;
  feasible: number;
  maxOverFlag: number;
  current: { metrics: Metrics };
  best: unknown;
  lowestOverFlag: { thresholds: typeof THRESHOLDS; metrics: Metrics } | null;
}>("eval/results/sweep-dev.json");
const rec = read<{
  thresholds: typeof THRESHOLDS;
  basis: { decision?: string; reason?: string; applied: boolean };
}>("eval/thresholds.recommended.json");
line("## Threshold sweep (dev split only)");
line();
if (sweep && rec) {
  line(
    `Grid: ${sweep.gridSize} points over the entailment-supported, entailment-partial, contradiction and unseen-word thresholds. Rule: maximise recall subject to over-flag <= ${pct(sweep.maxOverFlag, 0)}. Points that met the limit: **${sweep.feasible}**.`,
  );
  line();
  if (rec.basis.decision === "keep-current") {
    line(
      `**Recommendation: keep the current thresholds** (\`${JSON.stringify(THRESHOLDS)}\`). ${rec.basis.reason ?? ""}`,
    );
    if (sweep.lowestOverFlag) {
      line();
      line(
        `For information, the least over-flagging point that still catches >= 90% was \`${JSON.stringify(sweep.lowestOverFlag.thresholds)}\` at ${fmtRate(sweep.lowestOverFlag.metrics.overFlag)}, against ${fmtRate(sweep.current.metrics.overFlag)} now: one draft.`,
      );
    }
  } else {
    line(
      `Recommendation written to \`eval/thresholds.recommended.json\`: \`${JSON.stringify(rec.thresholds)}\`. It has **not** been applied to \`src/core/verify/thresholds.ts\`.`,
    );
  }
} else {
  line("The sweep has not been run.");
}
line();

line("## Why the verifier over-flags: what fired on good drafts");
line();
line(
  'A flagged good draft can have several causes. "Still flagged without X" is how many would remain if that one check were removed completely: it shows whether a single fix could reach the 15% target (<= 5 of 36).',
);
line();
line(
  "| split | judge | good drafts flagged | by judge | by entailment | by contradiction | by wording list | by unseen words | flagged by exactly one cause |",
);
line("|---|---|---:|---:|---:|---:|---:|---:|---:|");
for (const [name, r] of [
  ["dev", devLive],
  ["test", testLive],
] as const) {
  if (!r) continue;
  const b = overFlagBreakdown(r.results);
  line(
    `| ${name} | live | ${b.flagged}/${b.good} | ${b.byCause.judge ?? 0} | ${b.byCause.entailment ?? 0} | ${b.byCause.contradiction ?? 0} | ${b.byCause["wording list"] ?? 0} | ${b.byCause["unseen words"] ?? 0} | ${b.onlyOne} |`,
  );
}
line();
if (devLive) {
  const b = overFlagBreakdown(devLive.results);
  line(
    `Dev, still flagged if one cause were removed entirely: ${(Object.entries(b.remainingWithout) as [string, number][]).map(([k, v]) => `without ${k} ${v}/${b.good}`).join("; ")}.`,
  );
  line();
}

line("## Comparisons (dev split)");
line();
line("| configuration | recall | rejected outright | over-flag | bad passed as SUPPORTED |");
line("|---|---|---|---|---|");
for (const [name, r] of [
  ["small entailment model, neutral judge (current)", devFake],
  ["xsmall entailment model, neutral judge", devXs],
  ["small entailment model + Nara judge (nemotron-3.5-lightning-free)", devLive],
  ["small entailment model + OpenRouter judge (nemotron-3-ultra-550b)", devOr],
] as const) {
  if (!r) {
    line(
      `| ${name} | not run: the provider's free daily limit (50 requests) was already used up | | | |`,
    );
    continue;
  }
  line(
    `| ${name} | ${sCell(r, (m) => m.recall)} | ${sCell(r, (m) => m.hardRecall)} | ${sCell(r, (m) => m.overFlag)} | ${r.summary.slipped} |`,
  );
}
line();
for (const [name, r] of [
  ["Nara judge", devLive],
  ["OpenRouter judge", devOr],
] as const) {
  if (!r) continue;
  const judged = r.results.filter((x) => x.checks.judge.status === "ok");
  const goodOk = judged.filter(
    (x) =>
      x.label === "good" && x.checks.judge.status === "ok" && x.checks.judge.outcome === "pass",
  ).length;
  const goodN = judged.filter((x) => x.label === "good").length;
  const badCaught = judged.filter(
    (x) => x.label === "bad" && x.checks.judge.status === "ok" && x.checks.judge.outcome !== "pass",
  ).length;
  const badN = judged.filter((x) => x.label === "bad").length;
  line(
    `- ${name} alone: passed ${goodOk}/${goodN} good drafts (false-reject rate ${pct(1 - goodOk / Math.max(1, goodN))}), caught ${badCaught}/${badN} bad drafts. Drafts where its call failed: ${r.meta.degradedDrafts}.`,
  );
}
line();

line("## Misses: bad drafts passed as SUPPORTED");
line();
for (const [name, r] of [
  ["dev, live judge", devLive],
  ["test, live judge", testLive],
  ["dev, neutral judge", devFake],
  ["test, neutral judge", testFake],
] as const) {
  if (!r) continue;
  const missed = r.results.filter((x) => x.label === "bad" && x.verdict === "SUPPORTED");
  line(`**${name}:** ${missed.length === 0 ? "none" : ""}`);
  for (const d of missed)
    line(
      `- \`${d.id}\` (${d.failureType}, entailment ${d.scores.entailment?.toFixed(2) ?? "n/a"}, judge ${d.scores.judge}): ${d.text}`,
    );
  line();
}

line("## What the verifier misses, and where it over-flags (in plain language)");
line();
line(
  existsSync("eval/analysis.md")
    ? readFileSync("eval/analysis.md", "utf8").trim()
    : "_No analysis written yet (eval/analysis.md)._",
);
line();

line("## Pipeline evaluation (human review)");
line();
const e2eFiles = existsSync("eval/review-sheet.csv")
  ? readFileSync("eval/review-sheet.csv", "utf8").split("\n").length - 2
  : 0;
const human = read<{
  labelled: number;
  kappa: { kappa: number };
  faithfulness: number;
  unsupportedSlip: number;
  questionQuality: number | null;
}>("eval/results/human-review.json");
if (human) {
  line(
    `Reviewed rows: ${human.labelled}. Cohen's kappa ${human.kappa.kappa.toFixed(2)}; faithfulness ${pct(human.faithfulness)} (target >= 95%); unsupported slip ${pct(human.unsupportedSlip)} (target <= 2%); question quality ${human.questionQuality === null ? "n/a" : pct(human.questionQuality)} (target >= 90%).`,
  );
} else {
  line(
    `**Not measured.** The generate-then-verify pipeline needs two human reviewers. \`npm run eval:e2e\` writes \`eval/review-sheet.csv\` (${e2eFiles > 0 ? `${e2eFiles} rows so far` : "not generated yet"}); once both reviewer columns are filled, \`npm run eval:kappa\` computes kappa, faithfulness, unsupported-slip rate and question quality. Until then none of those lore metrics has a number.`,
  );
}
line();

const regs = loadRegressions();
line("## Regression cases");
line();
line(
  `${regs.length} cases in \`eval/regressions/\` (errors found and fixed in earlier stages). \`npm run eval:ci\` runs them with every other case and fails if any is handled wrongly again, or if any draft that was handled correctly in \`eval/baseline.fake.json\` no longer is.`,
);
line();

writeFileSync("eval/RESULTS.md", `${out.join("\n")}\n`);
console.log(`Wrote eval/RESULTS.md (${out.length} lines)`);
